local t = require("t")
local data = require("data")

t.case("wild encounters count per area and species, shiny sticks", function()
  local d = data.new()
  t.ok(data.record_wild(d, 5, 21, 0, false))
  t.ok(data.record_wild(d, 5, 21, 0, true))
  t.ok(data.record_wild(d, 5, 21, 1, false))
  t.ok(data.record_wild(d, 6, 21, 0, false))
  local a = data.area(d, 5)
  t.eq(a.wild.s21f0.n, 2)
  t.eq(a.wild.s21f0.shiny, true)
  t.eq(a.wild.s21f1.n, 1)
  t.eq(a.wild.s21f0.caught, false)
  t.eq(data.area(d, 6).wild.s21f0.n, 1)
  t.ok(a.visited)
  local seen, caught = data.counts(a)
  t.eq(seen, 2)
  t.eq(caught, 0)
end)

t.case("bad input is refused", function()
  local d = data.new()
  t.ok(not data.record_wild(d, "5", 21, 0))
  t.ok(not data.record_wild(d, 5, 0, 0))
  t.ok(not data.record_wild(d, 5, 21.5, 0))
  t.eq(next(d.areas), nil)
end)

t.case("trainers and caught", function()
  local d = data.new()
  data.record_trainer(d, 5, 30, 0)
  data.record_wild(d, 5, 21, 0)
  t.ok(data.mark_caught(d, 5, 21, 0))
  t.ok(not data.mark_caught(d, 5, 21, 0), "already caught")
  t.ok(not data.mark_caught(d, 5, 99, 0), "not seen")
  t.ok(not data.mark_caught(d, 8, 21, 0), "unknown area")
  local seen, caught, trainers = data.counts(data.area(d, 5))
  t.eq({ seen, caught, trainers }, { 1, 1, 1 })
  t.eq(data.area(d, 5).trainers.s30f0.caught, nil)
end)

t.case("visit and notes", function()
  local d = data.new()
  t.ok(data.visit(d, 7))
  t.ok(not data.visit(d, 7))
  t.ok(data.set_note(d, 7, "bring repels"))
  t.eq(data.area(d, 7).notes, "bring repels")
  t.ok(not data.set_note(d, 8, ""), "an empty note does not create an area")
  t.eq(data.area(d, 8), nil)
  data.set_note(d, 7, string.rep("x", data.MAX_NOTE + 50))
  t.eq(#data.area(d, 7).notes, data.MAX_NOTE)
  t.ok(data.has_data(data.area(d, 7)))
end)

t.case("limits", function()
  local d = data.new()
  for i = 1, data.MAX_AREAS do t.ok(data.visit(d, i)) end
  t.ok(not data.visit(d, data.MAX_AREAS + 1))
  local e = data.new()
  for s = 1, data.MAX_SPECIES do t.ok(data.record_wild(e, 1, s, 0)) end
  t.ok(not data.record_wild(e, 1, data.MAX_SPECIES + 1, 0))
  t.ok(data.record_wild(e, 1, 1, 0), "known species still count")
end)

t.case("seen species across areas and kinds", function()
  local d = data.new()
  data.record_wild(d, 5, 21, 0)
  data.record_trainer(d, 6, 21, 0)
  data.record_trainer(d, 6, 30, 2)
  local seen = data.seen_species(d)
  t.eq(seen, { s21f0 = { species = 21, form = 0 }, s30f2 = { species = 30, form = 2 } })
end)

t.case("sanitize keeps valid data and drops garbage", function()
  local d = data.new()
  data.record_wild(d, 5, 21, 0, true); data.mark_caught(d, 5, 21, 0); data.record_trainer(d, 5, 30, 0)
  data.set_note(d, 5, "n")
  t.eq(data.sanitize(data.copy(d)), d)
  t.eq(data.sanitize(nil), nil)
  t.eq(data.sanitize({ v = 2, areas = {} }), nil)
  local bad = data.sanitize({ v = 1, areas = { a = { zone = "x" }, b = { zone = 3, notes = 5, visited = "yes",
    wild = { { species = -1 }, { species = 4, form = -2, n = 0, caught = true } }, trainers = "no" } } })
  local a = data.area(bad, 3)
  t.eq(a.notes, "")
  t.eq(a.visited, false)
  t.eq(a.wild.s4f0, { species = 4, form = 0, n = 1, caught = true, shiny = false })
  t.eq(data.area(bad, 0), nil)
end)

t.case("merge loses nothing", function()
  local a, b = data.new(), data.new()
  data.record_wild(a, 5, 21, 0); data.record_wild(a, 5, 21, 0); data.set_note(a, 5, "mine")
  data.record_wild(b, 5, 21, 0); data.mark_caught(b, 5, 21, 0); data.record_wild(b, 6, 22, 0); data.set_note(b, 5, "theirs")
  data.record_trainer(b, 5, 30, 0)
  local m = data.merge(a, b)
  t.eq(data.area(m, 5).wild.s21f0, { species = 21, form = 0, n = 2, caught = true, shiny = false })
  t.ok(data.area(m, 6).wild.s22f0)
  t.ok(data.area(m, 5).trainers.s30f0)
  t.eq(data.area(m, 5).notes, "mine\n---\ntheirs")
  t.eq(data.merge(m, b), m, "merging again changes nothing")
  t.eq(data.merge(m, a), m)
  t.eq(data.area(a, 5).notes, "mine", "inputs are not changed")
end)
